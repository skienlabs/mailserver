#!/usr/bin/env python3
"""Builds web/static/js/icons.js (an inline SVG sprite) from @material-design-icons/svg.

Usage: npm pack @material-design-icons/svg && tar xzf material-design-icons-svg-*.tgz
       python3 tools/gen_icons.py package
"""
import re, sys, json, pathlib

OUTLINED = """menu search close edit inbox star star_border send archive report delete delete_forever
restore_from_trash mail mark_email_unread mark_email_read drafts refresh arrow_back chevron_left chevron_right
more_vert reply reply_all forward attach_file image settings logout admin_panel_settings person group dns schedule
receipt_long tune light_mode dark_mode check check_circle error warning info content_copy add person_add download
visibility visibility_off format_bold format_italic format_underlined format_strikethrough format_list_bulleted
format_list_numbered link format_quote format_clear remove open_in_full close_fullscreen expand_more expand_less label
all_inbox beach_access lock key devices upload keyboard install_desktop contacts dashboard outbox description
picture_as_pdf folder_zip insert_drive_file shield account_circle badge verified_user undo filter_list
desktop_windows phone_iphone language notifications move_to_inbox unfold_more south_west north_east report_off
mail_outline alternate_email domain storage speed bolt cloud_off sync_alt""".split()
FILLED = "inbox star send archive report delete drafts insert_drive_file all_inbox contacts dashboard person group dns schedule receipt_long tune settings check_circle error warning".split()

root = pathlib.Path(sys.argv[1] if len(sys.argv) > 1 else "package")
syms = []
def add(name, style, sid):
    svg = (root / style / f"{name}.svg").read_text()
    inner = re.search(r"<svg[^>]*>(.*)</svg>", svg, re.S).group(1)
    vb = re.search(r'viewBox="([^"]+)"', svg).group(1)
    syms.append(f'<symbol id="i-{sid}" viewBox="{vb}">{inner}</symbol>')
for n in OUTLINED:
    add(n, "outlined", n)
for n in FILLED:
    add(n, "filled", n + "-f")
sprite = '<svg xmlns="http://www.w3.org/2000/svg" style="display:none">' + "".join(syms) + "</svg>"
out = pathlib.Path(__file__).resolve().parent.parent / "web/static/js/icons.js"
out.write_text("// Generated by tools/gen_icons.py from Material Design Icons (Apache-2.0). Do not edit.\nexport const SPRITE = " + json.dumps(sprite) + ";\n")
print(f"{len(syms)} icons -> {out} ({out.stat().st_size} bytes)")
